    $sidebarInPage = ($pageText -match $SidebarPattern) -or ($pageText -match $ShellImportPattern)

    if (-not $sidebarInPage) {
        # Sidebar layout me hai -> page.tsx ko seedha live dashboard se badal do
        $target = $AdminPage
        if ($AdminPage -notlike "*.tsx") {
            # page.js / page.jsx ko backup me le jao, nayi page.tsx banao
            $bk = Join-Path $BackupDir ($AdminPage.Substring($Root.Length).TrimStart("\"))
            New-Item -ItemType Directory -Force -Path (Split-Path $bk) | Out-Null
            Move-Item -LiteralPath $AdminPage -Destination $bk -Force
            $target = Join-Path $AppDir "admin\page.tsx"
        }
        Write-TextFile $target $WrapperPage
        $DashboardDone = $true
    } else {
        # Sidebar page ke andar hai -> sirf dummy data wali component file badlo (agar safe ho)
        $dummyFiles = @(
            @(Find-ProjectFiles "*.tsx") | Where-Object {
                $_.FullName -ne $AdminPage -and (Get-Content -LiteralPath $_.FullName -Raw) -match $DummyPattern
            }
        )
        foreach ($d in $dummyFiles) {
            $t = Get-Content -LiteralPath $d.FullName -Raw
            $exportCount = ([regex]::Matches($t, '(?m)^\s*export\s')).Count
            $hasDefault = $t -match '(?m)^\s*export\s+default'
            if ($hasDefault -and $exportCount -eq 1 -and -not ($t -match $SidebarPattern)) {
                Write-TextFile $d.FullName $WrapperComponent
                $DashboardDone = $true
            }
        }
    }
} else {
    $DashboardNote = "app\admin\page.tsx nahi mila"
}

if ($DashboardDone) {
    Say "  OK      Admin dashboard ab LIVE data dikhayega." Green
} else {
    # Safe tareeke se badal nahi sakte -> files ek zip me Desktop par rakh do
    $collect = @()
    if ($AdminPage) { $collect += $AdminPage }
    foreach ($n in @("layout.tsx", "layout.jsx", "layout.js")) {
        $l = Join-Path $AppDir ("admin\" + $n); if (Test-Path $l) { $collect += $l }
    }
    $collect += @(Find-ProjectFiles "*.tsx" | Where-Object { (Get-Content -LiteralPath $_.FullName -Raw) -match "$DummyPattern|$SidebarPattern" } | ForEach-Object { $_.FullName })
    $collect = @($collect | Select-Object -Unique | Select-Object -First 20)
    $desktop = [Environment]::GetFolderPath("Desktop")
    if (-not $desktop -or -not (Test-Path $desktop)) { $desktop = $Root }
    $zip = Join-Path $desktop "Fresh2Cook-admin-files.zip"
    if ($collect.Count -gt 0) {
        $tmpBase = $env:TEMP; if (-not $tmpBase) { $tmpBase = [IO.Path]::GetTempPath() }
        $tmp = Join-Path $tmpBase ("f2c-admin-" + $Stamp)
        New-Item -ItemType Directory -Force -Path $tmp | Out-Null
        foreach ($f in $collect) {
            $rel = $f.Substring($Root.Length).TrimStart("\")
            $dest = Join-Path $tmp $rel
            New-Item -ItemType Directory -Force -Path (Split-Path $dest) | Out-Null
            Copy-Item -LiteralPath $f -Destination $dest -Force
        }
        Compress-Archive -Path (Join-Path $tmp "*") -DestinationPath $zip -Force
    }
    $Skipped += "Admin dashboard page ko safe tareeke se nahi badal paye. $DashboardNote"
    Say "  RUKO    Admin page ka structure alag hai, isliye use nahi chheda." Yellow
    if ($collect.Count -gt 0) { Say "          Yeh file Claude ko bhejein:  $zip" Yellow }
}

