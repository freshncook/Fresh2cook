# ---------- 2. Helper: backup + write ----------
function Write-ProjectFile([string]$Target, [string]$Base64) {
    $bytes = [Convert]::FromBase64String($Base64)
    $rel = $Target.Substring($Root.Length).TrimStart("\")

    if (Test-Path $Target) {
        $backupPath = Join-Path $BackupDir $rel
        New-Item -ItemType Directory -Force -Path (Split-Path $backupPath) | Out-Null
        Copy-Item -LiteralPath $Target -Destination $backupPath -Force
        $script:Updated += $rel
        Say "  UPDATE  $rel" Green
    } else {
        $script:Created += $rel
        Say "  NEW     $rel" Yellow
    }

    New-Item -ItemType Directory -Force -Path (Split-Path $Target) | Out-Null
    [System.IO.File]::WriteAllBytes($Target, $bytes)
}

# Project ke andar files dhundho (node_modules, .next, _backups chhod kar)
function Find-ProjectFiles([string]$Name) {
    $skip = @("node_modules", ".next", "_backups", ".git")
    $results = @()
    $results += Get-ChildItem -LiteralPath $Root -File -Filter $Name -ErrorAction SilentlyContinue
    Get-ChildItem -LiteralPath $Root -Directory -ErrorAction SilentlyContinue |
        Where-Object { $skip -notcontains $_.Name } |
        ForEach-Object {
            $results += Get-ChildItem -LiteralPath $_.FullName -Recurse -File -Filter $Name -ErrorAction SilentlyContinue |
                Where-Object { $_.FullName -notmatch '\\(node_modules|\.next|_backups|\.git)\\' }
        }
    return $results
}

